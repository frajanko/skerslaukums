    /// Veidaugstums, m: tabulā — lineāra interpolācija; ārpus 9–40 m — lineāra ekstrapolācija.
    static func hf(species: String, h: Double) -> Double? {
        guard let t = table[column(species)], h > 1.3 else { return nil }
        let x = h - hMin
        let i = min(max(Int(x.rounded(.down)), 0), t.count - 2)
        let v = t[i] + (t[i + 1] - t[i]) * (x - Double(i))
        return v > 0 ? v : nil
    }

    static func inTable(_ h: Double) -> Bool { h >= hMin && h <= hMax }
