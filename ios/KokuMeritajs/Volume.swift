    /// Kura tabulas kolonna attiecas uz sugu.
    static func column(_ species: String) -> String {
        switch species {
        case "P", "E", "B", "M", "A", "O", "Os": return species
        default: return "Ba"   // liepa, kļava, citi — „baltalksnis un citi lapu koki”
